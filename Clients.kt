package com.ppp65isking.ytmusicfortv.innertube

import java.time.LocalDate
import java.time.format.DateTimeFormatter

/**
 * InnerTube client definitions.
 *
 * Verified live against yt-dlp's `yt_dlp/extractor/youtube/_base.py` on
 * 2026-11-08 (see phase1-report.md). When YouTube breaks playback, re-pull
 * the versions from yt-dlp first — never guess them.
 *
 * Phase 1 correction to the original plan: the dual-client trick's mobile
 * half is DEAD. IOS/ANDROID player calls return SABR-only formats (no plain
 * url). The only proven player client is VISIONOS. No API key is needed
 * (ytmusicapi's WEB_REMIX key is literally `<redacted>` in its source).
 */
object Clients {

    data class ClientDef(
        val clientName: String,
        val clientId: Int,
        val clientVersion: String,
        val userAgent: String,
        val deviceMake: String? = null,
        val deviceModel: String? = null,
        val osName: String? = null,
        val osVersion: String? = null,
        val androidSdkVersion: Int? = null,
    )

    /** WEB_REMIX version is date-generated by ytmusicapi: 1.YYYYMMDD.01.00 */
    fun webRemixVersion(): String =
        "1." + LocalDate.now().format(DateTimeFormatter.BASIC_ISO_DATE) + ".01.00"

    /** Search / browse metadata. Any modern browser UA works. */
    val WEB_REMIX: ClientDef
        get() = ClientDef(
            clientName = "WEB_REMIX",
            clientId = 67,
            clientVersion = webRemixVersion(),
            userAgent = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) " +
                "AppleWebKit/537.36 (KHTML, like Gecko) " +
                "Chrome/126.0.0.0 Safari/537.36",
        )

    /** THE player client. Returns plain stream URLs + hlsManifestUrl. */
    val VISIONOS = ClientDef(
        clientName = "VISIONOS",
        clientId = 101,
        clientVersion = "1.02",
        userAgent = "Mozilla/5.0 (Macintosh; Intel Mac OS X 15_7_3) " +
            "AppleWebKit/605.1.15 (KHTML, like Gecko) " +
            "Version/26.0 Safari/605.1.15",
        deviceMake = "Apple",
        deviceModel = "RealityDevice17,1",
        osName = "visionOS",
        osVersion = "26.5.23O471",
    )

    /** Reference only: SABR-only since ~2026, no plain URLs. Do not use. */
    val IOS = ClientDef(
        clientName = "IOS",
        clientId = 5,
        clientVersion = "21.26.4",
        userAgent = "com.google.ios.youtube/21.26.4 " +
            "(iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X;)",
        deviceMake = "Apple",
        deviceModel = "iPhone16,2",
        osName = "iOS",
        osVersion = "18.3.2",
    )

    /** Reference only: SABR-only since ~2026, no plain URLs. Do not use. */
    val ANDROID = ClientDef(
        clientName = "ANDROID",
        clientId = 3,
        clientVersion = "21.26.364",
        userAgent = "com.google.android.youtube/21.26.364 " +
            "(Linux; U; Android 11) gzip",
        deviceMake = "Google",
        deviceModel = "Pixel 5",
        osName = "Android",
        osVersion = "11",
        androidSdkVersion = 30,
    )
}
